vim.keymap.set("i", "<C-c>", "<Esc>")

vim.keymap.set("n", "Q", "<nop>")
-- Launch tmux-sessionizer in a new window rooted at Neovim's cwd, so the
-- ($PWD-relative) picker browses relative to the project you're editing.
vim.keymap.set("n", "<C-f>", function()
  vim.cmd("silent !tmux neww -c " .. vim.fn.shellescape(vim.fn.getcwd()) .. " tmux-sessionizer")
end)

vim.keymap.set("n", "<C-k>", "<cmd>cnext<CR>zz")
vim.keymap.set("n", "<C-j>", "<cmd>cprev<CR>zz")
vim.keymap.set("n", "<leader>k", "<cmd>lnext<CR>zz")
vim.keymap.set("n", "<leader>j", "<cmd>lprev<CR>zz")

vim.keymap.set("n", "<leader>e", vim.diagnostic.open_float, { silent = true })

vim.keymap.set("n", "<leader>s", [[:%s/\<<C-r><C-w>\>/<C-r><C-w>/gI<Left><Left><Left>]])
vim.keymap.set("n", "<leader>x", "<cmd>!chmod +x %<CR>", { silent = true })

-- Source the current file (handy while editing config)
vim.keymap.set("n", "<leader><leader>", function()
  vim.cmd("so")
end)
